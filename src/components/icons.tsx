import {
  ArrowRight,
  CalendarDays,
  CalendarMinus,
  CalendarPlus,
  Check,
  CheckCircle2,
  Copy,
  ExternalLink,
  Hash,
  Inbox,
  Keyboard,
  Moon,
  Plus,
  Settings,
  Sparkles,
  Sun,
  SunMedium,
  Sunrise,
  Target,
  Trash2,
  type LucideIcon,
  Archive,
  CalendarRange,
  Folder,
  PanelRight,
  Search,
  Timer,
  Zap,
  Gauge,
} from "lucide-react";

export const ICONS: Record<string, LucideIcon> = {
  check: Check,
  open: ExternalLink,
  focus: Target,
  today: Sun,
  tomorrow: Sunrise,
  calendar: CalendarDays,
  someday: Archive,
  unschedule: CalendarMinus,
  inbox: Inbox,
  copy: Copy,
  trash: Trash2,
  plus: Plus,
  event: CalendarPlus,
  upcoming: CalendarRange,
  done: CheckCircle2,
  project: Folder,
  tag: Hash,
  settings: Settings,
  plan: Sparkles,
  theme: Moon,
  light: SunMedium,
  keyboard: Keyboard,
  panel: PanelRight,
  search: Search,
  timer: Timer,
  go: ArrowRight,
  quick: Zap,
  rating: Gauge,
};

export function MenuIcon({ name, size = 15 }: { name?: string; size?: number }) {
  if (!name) return null;
  const I = ICONS[name];
  return I ? <I size={size} /> : null;
}
